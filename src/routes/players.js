// Validation helper
function validatePlayerData(data, isUpdate = false) {
  const { name, age, sport, registeredOn, defaultParticipation } = data;

  if (!isUpdate || name !== undefined) {
    if (!name || typeof name !== 'string' || !name.trim()) {
      return 'Player name is required';
    }
  }

  if (!isUpdate || age !== undefined) {
    const numAge = Number(age);
    if (age === undefined || age === null || isNaN(numAge) || numAge < 5 || numAge > 50) {
      return 'Age must be a number between 5 and 50';
    }
  }

  if (!isUpdate || sport !== undefined) {
    if (!sport || typeof sport !== 'string' || !sport.trim()) {
      return 'Sport is required';
    }
  }

  if (registeredOn !== undefined && registeredOn !== null) {
    const regDate = new Date(registeredOn);
    if (isNaN(regDate.getTime())) {
      return 'registeredOn must be a valid date';
    }
    // Cannot be in the future (allow 60s tolerance)
    if (regDate.getTime() > Date.now() + 60000) {
      return 'registeredOn cannot be in the future';
    }
  }

  if (defaultParticipation !== undefined && defaultParticipation !== null) {
    if (!['practice', 'match', 'both'].includes(defaultParticipation)) {
      return 'defaultParticipation must be practice, match, or both';
    }
  }

  return null;
}

// ── POST /api/players  (admin or coach) ──────────────────────
const recentIdempotencyKeys = new Map();
// Cleanup keys older than 5 minutes periodically
setInterval(() => {
  const fiveMinAgo = Date.now() - 300000;
  for (const [k, v] of recentIdempotencyKeys.entries()) {
    if (v.timestamp < fiveMinAgo) recentIdempotencyKeys.delete(k);
  }
}, 60000);

router.post('/', allow('admin', 'coach'), async (req, res) => {
  let createdPlayer = null;
  try {
    const idempotencyKey = req.headers['x-idempotency-key'] || req.body.idempotencyKey;
    if (idempotencyKey && recentIdempotencyKeys.has(idempotencyKey)) {
      const cached = recentIdempotencyKeys.get(idempotencyKey);
      return res.status(cached.status).json(cached.body);
    }

    const error = validatePlayerData(req.body, false);
    if (error) {
      return res.status(400).json({ error });
    }

    const { name, age, sport, registeredOn, defaultParticipation } = req.body;
    const coachId = await resolveCoachId(req, req.body.coachId);
    if (!coachId) {
      return res.status(400).json({
        error: 'No coach account is available. Create a coach before registering players.'
      });
    }

    // Guard against accidental double clicks / rapid duplicate submissions within 15 seconds
    const fifteenSecondsAgo = new Date(Date.now() - 15000);
    const escapedName = name.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const rapidDuplicate = await Player.findOne({
      coach: coachId,
      name: new RegExp('^' + escapedName + '$', 'i'),
      sport: sport.trim(),
      age: Number(age),
      createdAt: { $gte: fifteenSecondsAgo }
    });
    if (rapidDuplicate) {
      return res.status(409).json({
        error: 'A player with this name, age, and sport was just registered. Duplicate submission prevented.'
      });
    }

    const { generateSecureTemporaryPassword } = require('../utils/credentials');
    const tempPassword = generateSecureTemporaryPassword();

    // 1. Create Player record (pre-save hook in Player.js assigns unique playerId and username)
    // Server/backend date is always the authoritative registration date unless explicitly passed by admin migration/scripts
    const effectiveRegistrationDate = (req.user.role === 'admin' && registeredOn) ? new Date(registeredOn) : new Date();

    createdPlayer = await Player.create({
      name: name.trim(),
      age: Number(age),
      sport: sport.trim(),
      registeredOn: effectiveRegistrationDate,
      defaultParticipation: defaultParticipation || 'both',
      coach: coachId
    });

    // 2. Reuse the exact username generated by Player.js
    const playerUsername = (createdPlayer.username || createdPlayer.playerId).toLowerCase();

    // 3. Ensure no colliding User account exists before creation
    const existingUser = await User.findOne({
      $or: [
        { playerId: createdPlayer._id },
        { username: playerUsername }
      ]
    });
    if (existingUser) {
      // Rollback newly created player
      await Player.findByIdAndDelete(createdPlayer._id);
      createdPlayer = null;
      return res.status(409).json({ error: 'User account already exists for this username/player.' });
    }

    // 4. Create User account with role PLAYER and mustChangePassword = true
    // Note: User.js pre-save hook will securely hash tempPassword with bcrypt
    try {
      await User.create({
        name: createdPlayer.name,
        username: playerUsername,
        email: `${playerUsername}@player.com`,
        password: tempPassword,
        role: 'player',
        playerId: createdPlayer._id,
        mustChangePassword: true
      });
    } catch (userErr) {
      // Safe Rollback Strategy: delete newly created Player if User creation fails
      if (createdPlayer && createdPlayer._id) {
        await Player.findByIdAndDelete(createdPlayer._id);
        createdPlayer = null;
      }
      return res.status(500).json({
        error: `Failed to create player login credentials: ${userErr.message}. Registration rolled back.`
      });
    }

    // 5. Auto-sync newly created player to any active/unlocked sessions
    try {
      const activeSessions = await Session.find({
        coach: coachId,
        sport: sportRegex(createdPlayer.sport),
        saved: false,
        locked: false
      });

      for (const s of activeSessions) {
        const alreadyInSession = (s.attendance || []).some(
          a => (a.player?._id || a.player).toString() === createdPlayer._id.toString()
        );
        if (!alreadyInSession) {
          s.attendance.push({
            player: createdPlayer._id,
            status: 'present',
            participation: createdPlayer.defaultParticipation || 'both'
          });
          if (!(s.initialRosterPlayerIds || []).some(id => id.toString() === createdPlayer._id.toString())) {
            s.initialRosterPlayerIds.push(createdPlayer._id);
          }
          s.createdWithCount = s.attendance.length;
          await s.save();
        }
      }
    } catch (sessionSyncErr) {
      console.error('Error auto-syncing new player to active sessions:', sessionSyncErr);
    }

    broadcastServerSync({ entity: 'player', action: 'created', entityId: createdPlayer._id.toString() });

    const responsePayload = {
      ...createdPlayer.toObject(),
      credentials: {
        username: playerUsername,
        temporaryPassword: tempPassword,
        mustChangePassword: true
      }
    };

    if (idempotencyKey) {
      recentIdempotencyKeys.set(idempotencyKey, { status: 201, body: responsePayload, timestamp: Date.now() });
    }

    res.status(201).json(responsePayload);
  } catch (err) {
    // If player was created but unexpected error occurred, rollback
    if (createdPlayer && createdPlayer._id) {
      try {
        await Player.findByIdAndDelete(createdPlayer._id);
      } catch (_) {}
    }
    res.status(400).json({ error: err.message });
  }
});

// ── GET /api/players  ─────────────────────────────────────────
router.get('/', async (req, res) => {
  try {
    let players;

    if (req.user.role === 'admin') {
      players = await Player.find().populate('coach', 'name');
    } else if (req.user.role === 'coach') {
      players = await Player.find({ coach: req.user.id }).populate('coach', 'name');
    } else if (req.user.role === 'scout') {
      const allPlayers = await Player.find().populate('coach', 'name');
      const enriched = await enrichPlayersBatch(allPlayers);
      return res.json(enriched.filter(p => p.isReady));
    } else {
      // Player role sees only themselves
      const p = await Player.findById(req.user.playerId);
      const list = p ? [await enrichPlayer(p)] : [];
      return res.json(list);
    }

    const enriched = await enrichPlayersBatch(players);
    res.json(enriched);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── GET /api/players/me  (player) ─────────────────────────────
router.get('/me', async (req, res) => {
  try {
    if (!req.user.playerId) {
      return res.status(404).json({ error: 'No player profile associated with this account' });
    }
    const player = await Player.findById(req.user.playerId).populate('coach', 'name');
    if (!player) return res.status(404).json({ error: 'Player not found' });
    res.json(await enrichPlayer(player));
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── GET /api/players/:id  ─────────────────────────────────────
router.get('/:id', async (req, res) => {
  try {
    const isObjectId = mongoose.Types.ObjectId.isValid(req.params.id);
    const filter = isObjectId
      ? { $or: [{ _id: req.params.id }, { playerId: req.params.id.toLowerCase() }, { username: req.params.id.toLowerCase() }] }
      : { $or: [{ playerId: req.params.id.toLowerCase() }, { username: req.params.id.toLowerCase() }] };

    const player = await Player.findOne(filter).populate('coach', 'name');
    if (!player) return res.status(404).json({ error: 'Player not found' });

    if (req.user.role === 'player' && req.user.playerId?.toString() !== player._id.toString()) {
      return res.status(403).json({ error: 'Forbidden' });
    }
    res.json(await enrichPlayer(player));
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── PATCH /api/players/:id  (admin or the player's coach) ─────
router.patch('/:id', allow('admin', 'coach'), async (req, res) => {
  try {
    const isObjectId = mongoose.Types.ObjectId.isValid(req.params.id);
    const filter = isObjectId
      ? { $or: [{ _id: req.params.id }, { playerId: req.params.id.toLowerCase() }, { username: req.params.id.toLowerCase() }] }
      : { $or: [{ playerId: req.params.id.toLowerCase() }, { username: req.params.id.toLowerCase() }] };

    const player = await Player.findOne(filter);
    if (!player) return res.status(404).json({ error: 'Player not found' });
    if (req.user.role === 'coach' && player.coach.toString() !== req.user.id) {
      return res.status(403).json({ error: 'Forbidden' });
    }

    const error = validatePlayerData(req.body, true);
    if (error) {
      return res.status(400).json({ error });
    }

    const { name, age, sport, registeredOn, defaultParticipation } = req.body;
    if (name !== undefined) player.name = name.trim();
    if (age !== undefined) player.age = Number(age);
    if (sport !== undefined) player.sport = sport.trim();
    if (registeredOn !== undefined) player.registeredOn = new Date(registeredOn);
    if (defaultParticipation !== undefined) player.defaultParticipation = defaultParticipation;

    await player.save();

    // Synchronize name update to linked user accounts
    if (name !== undefined) {
      await User.updateMany({ playerId: player._id }, { name: player.name });
    }

    broadcastServerSync({ entity: 'player', action: 'updated', entityId: player._id.toString() });
    res.json(await enrichPlayer(player));
  } catch (err) {
    res.status(400).json({ error: err.message });
  }
});

